// Bundles the blog prompt data for the Supabase Edge Function.
//
// server/data/blog/{style.md,facts.md,images.json} stay the single source of
// truth. Deno cannot read loose files that nothing imports, so this writes them
// into one JSON module the function imports. `npm run blog:deploy` regenerates
// it before deploying, and a test fails if the committed copy has drifted.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(root, "server", "data", "blog");
export const OUT = path.join(root, "supabase", "functions", "_shared", "prompt-data.json");

export function buildPromptData() {
  return {
    _comment: "Generated by scripts/build-edge-blog-data.mjs from server/data/blog. Do not edit by hand.",
    style: fs.readFileSync(path.join(DATA, "style.md"), "utf8"),
    facts: fs.readFileSync(path.join(DATA, "facts.md"), "utf8"),
    imagePool: JSON.parse(fs.readFileSync(path.join(DATA, "images.json"), "utf8")),
  };
}

export const serialise = (data) => JSON.stringify(data, null, 2) + "\n";

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = serialise(buildPromptData());
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(root, OUT)} (${text.length} bytes)`);
}
